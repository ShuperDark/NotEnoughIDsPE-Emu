"""Generates src/NotEnoughIDsPE.cpp from the jailbreak tweak's Tweak.xm.

The tweak's logic (every patch site, check and API function) is kept as it is; only the
iOS / Theos specific parts are replaced by the port layer (src/neid_port.h):

  - Logos (%ctor), MobileSubstrate (MSHookFunction, MSFindSymbol / MSHookMemory),
    Objective-C logging (NSLog, NSString)
  - write_memory / sys_icache_invalidate
  - the cave area in the tweak's own __TEXT and the branch helpers encB / encBL /
    inBRange (the emulator loads mods far away from the game, see neid_port.h)

Usage:
    py tools/port_tweak.py [path/to/Tweak.xm]
Default source: ../NotEnoughIDsPE/Tweak.xm (a clone of
https://github.com/ShuperDark/NotEnoughIDsPE next to this folder)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(os.path.dirname(ROOT), "NotEnoughIDsPE", "Tweak.xm")
OUT = os.path.join(ROOT, "src", "NotEnoughIDsPE.cpp")

HEADER = """\
// NotEnoughIDsPE for the iOS MCPE (v0.16.2) Emulator.
//
// GENERATED by tools/port_tweak.py from the jailbreak tweak's Tweak.xm - do not edit by
// hand; change the tweak (or the port layer src/neid_port.h / neid_port.cpp) and run
//     py tools/port_tweak.py
// again. Only the iOS-specific parts were replaced (see neid_port.h); every patch site,
// check and API function is the tweak's own code.
#include "neid_port.h"

#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <functional>
#include <map>
#include <memory>
#include <mutex>
#include <random>
#include <string>
#include <tuple>
#include <unordered_map>
#include <vector>
#include <math.h>
"""


def fail(msg):
    sys.exit("port_tweak.py: " + msg)


def replace_once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        fail(f"{what}: expected 1 match, found {n}")
    return text.replace(old, new)


def replace_block(text, start_re, what, new=""):
    """Replaces the function / definition starting at start_re (up to its matching brace)."""
    m = re.search(start_re, text, re.M)
    if not m:
        fail(f"{what}: not found")
    i = text.index("{", m.end() - 1 if text[m.end() - 1] == "{" else m.end())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                end = j + 1
                if end < len(text) and text[end] == "\n":
                    end += 1
                return text[: m.start()] + new + text[end:]
    fail(f"{what}: unbalanced braces")


def port(src):
    t = src.replace("\r\n", "\n")

    # 1. includes / imports (everything before the first banner comment)
    banner = t.index("// ============================================================================")
    head = t[:banner]
    if "#import" not in head or "substrate.h" not in head:
        fail("unexpected file header")
    t = HEADER + "\n" + t[banner:]

    # 2. memory writing: provided by the port layer
    t = re.sub(r"typedef void \(\*MSHookMemory_ptr_t\)\(void\* target, const void\* data, size_t size\);\n", "", t)
    t = replace_block(t, r"^static bool write_memory\(void\* destination, const void\* data, size_t size\) \{",
                      "write_memory", "// write_memory: see neid_port.h\n")

    # 3. logging: neidLog(NSString*) -> printf-style C function in the port layer
    t = replace_block(t, r"^static void neidLog\(NSString\* fmt, \.\.\.\) \{", "neidLog",
                      "// neidLog: see neid_port.cpp\n")

    # 4. the cave area in the tweak's __TEXT -> area next to the game (neidCaveArea macro)
    t = replace_block(t, r"^__attribute__\(\(naked, noinline\)\) static void neidCaveArea\(\) \{", "neidCaveArea",
                      "// neidCaveArea: allocated next to the game image, see neid_port.h\n")

    # 5. branch helpers -> versions that use veneers for far targets
    t = re.sub(r"^static inline uint32_t encB\(uint64_t from, uint64_t to\) \{.*\}\n",
               "// encB: see neid_port.h\n", t, count=1, flags=re.M)
    t = re.sub(r"^static inline bool inBRange\(uint64_t from, uint64_t to\) \{.*\}\n",
               "// inBRange: see neid_port.h\n", t, count=1, flags=re.M)
    t = re.sub(r"^static inline uint32_t encBL\(uint64_t from, uint64_t to\) \{.*\}\n",
               "// encBL: see neid_port.h\n", t, count=1, flags=re.M)
    for name in ("encB", "encBL", "inBRange"):
        if re.search(rf"^static inline \w+ {name}\(", t, re.M):
            fail(f"{name}: definition left over")

    # 6. Objective-C string literals -> C strings
    t = t.replace('@"', '"')
    if "NSString" in t or "[NS" in t:
        fail("Objective-C left over: " + t[t.find("NS") - 40: t.find("NS") + 40])

    # 7. Logos constructor
    t = replace_once(t, "%ctor {", "__attribute__((constructor)) static void neid_ctor() {", "%ctor")
    if re.search(r"^%", t, re.M):
        fail("Logos directive left over")

    return t


def main():
    src_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    with open(src_path, encoding="utf-8") as f:
        src = f.read()
    out = port(src)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"{src_path} -> {OUT} ({out.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
